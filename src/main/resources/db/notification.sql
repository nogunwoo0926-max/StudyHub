CREATE TABLE TB_NOTIFICATION (
    NOTIFICATION_ID NUMBER PRIMARY KEY,
    RECEIVER_ID VARCHAR2(100) NOT NULL,
    STUDY_ID NUMBER,
    TYPE VARCHAR2(30) NOT NULL,
    MESSAGE VARCHAR2(500) NOT NULL,
    IS_READ CHAR(1) DEFAULT 'N' NOT NULL,
    REG_DATE DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT FK_NOTIFICATION_MEMBER FOREIGN KEY (RECEIVER_ID) REFERENCES TB_MEMBER(ID),
    CONSTRAINT FK_NOTIFICATION_STUDY FOREIGN KEY (STUDY_ID) REFERENCES TB_STUDY(STUDY_ID),
    CONSTRAINT CK_NOTIFICATION_READ CHECK (IS_READ IN ('Y', 'N'))
);

CREATE SEQUENCE SEQ_NOTIFICATION START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE INDEX IDX_NOTIFICATION_RECEIVER ON TB_NOTIFICATION(RECEIVER_ID, IS_READ, REG_DATE);
